-- EOW growth analytics: additive-only schema change.
-- Tracks authenticated product activity and signup attribution for the admin dashboard.
create table if not exists public.eow_activity_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (event_type in (
    'signup','page_view','post_created','friend_request_sent',
    'community_joined','message_sent','invite_link_created','invite_accepted'
  )),
  page text check (page is null or char_length(page) <= 120),
  source text check (source is null or char_length(source) <= 120),
  campaign text check (campaign is null or char_length(campaign) <= 120),
  created_at timestamptz not null default now()
);

create index if not exists eow_activity_events_created_at_idx
  on public.eow_activity_events (created_at desc);
create index if not exists eow_activity_events_user_type_created_idx
  on public.eow_activity_events (user_id, event_type, created_at desc);
create index if not exists eow_activity_events_signup_source_idx
  on public.eow_activity_events (source, created_at desc)
  where event_type = 'signup';

alter table public.eow_activity_events enable row level security;

drop policy if exists "Users record own EOW activity" on public.eow_activity_events;
create policy "Users record own EOW activity"
  on public.eow_activity_events
  for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and event_type in (
      'signup','page_view','post_created','friend_request_sent',
      'community_joined','message_sent','invite_link_created','invite_accepted'
    )
  );

drop policy if exists "EOW admins read activity analytics" on public.eow_activity_events;
create policy "EOW admins read activity analytics"
  on public.eow_activity_events
  for select
  to authenticated
  using (
    exists (
      select 1 from public.eow_admins a
      where a.user_id = (select auth.uid())
    )
  );

grant select, insert on public.eow_activity_events to authenticated;
grant usage, select on sequence public.eow_activity_events_id_seq to authenticated;

comment on table public.eow_activity_events is
  'Authenticated product activity telemetry for EOW growth analytics; contains no message or post content.';
